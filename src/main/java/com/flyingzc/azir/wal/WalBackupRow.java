package com.flyingzc.azir.wal;

import java.util.Objects;

/**
 * The latest single key in the backend backup version, tombstone still carries the original commit serial number.
 *
 * @param key business key
 * @param version version
 */
public record WalBackupRow(String key, WalValue version) {

    /**
     * Rejects missing identity or illegal version and does not allow backup import of data that cannot be generated by normal transaction.
     *
     * @param key business key
     * @param version version
     * @throws IllegalArgumentException if the operation cannot complete
     */
    public WalBackupRow {
        Objects.requireNonNull(version);
        new WalMutation("backup", key, null);
        if (version.commitSequence() < 1 || version.valueLength() > 8 * 1024 * 1024) {
            throw new IllegalArgumentException("invalid backup version");
        }
    }
}
